import { execFileSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { chmodSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const envLocalPath = join(root, ".env.local");
const envPath = join(root, ".env");
const stripeConfigPath = join(homedir(), ".config/stripe/config.toml");

function parseEnv(path) {
  if (!existsSync(path)) return new Map();
  const entries = new Map();
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#") || !trimmed.includes("=")) continue;
    const index = trimmed.indexOf("=");
    entries.set(trimmed.slice(0, index), trimmed.slice(index + 1));
  }
  return entries;
}

function parseTomlValue(raw) {
  const value = raw.trim();
  if (value.startsWith('"') && value.endsWith('"')) return JSON.parse(value);
  if (value.startsWith("'") && value.endsWith("'")) return value.slice(1, -1);
  return value;
}

function readStripeProfile(profile = "default") {
  if (!existsSync(stripeConfigPath)) {
    throw new Error("Stripe CLI config not found. Run `stripe login` first.");
  }
  const values = new Map();
  let currentSection = "";
  for (const line of readFileSync(stripeConfigPath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    const section = trimmed.match(/^\[([^\]]+)\]$/);
    if (section) {
      currentSection = section[1];
      continue;
    }
    if (currentSection !== profile || !trimmed.includes("=")) continue;
    const index = trimmed.indexOf("=");
    values.set(
      trimmed.slice(0, index).trim(),
      parseTomlValue(trimmed.slice(index + 1))
    );
  }
  return values;
}

function usableSecret(value, prefix) {
  return typeof value === "string" && value.startsWith(prefix) && value.length > 20;
}

const stripeProfile = readStripeProfile();
const testSecretKey = stripeProfile.get("test_mode_api_key");
const testPublishableKey = stripeProfile.get("test_mode_pub_key");
if (!usableSecret(testSecretKey, "rk_test_") && !usableSecret(testSecretKey, "sk_test_")) {
  throw new Error("Stripe CLI test secret key is unavailable. Re-run `stripe login`.");
}
if (!usableSecret(testPublishableKey, "pk_test_")) {
  throw new Error("Stripe CLI test publishable key is unavailable.");
}

const webhookSecret = execFileSync(
  "stripe",
  ["listen", "--print-secret", "--skip-update"],
  { encoding: "utf8" }
).trim();
if (!usableSecret(webhookSecret, "whsec_")) {
  throw new Error("Stripe CLI did not return a webhook signing secret.");
}

const inherited = parseEnv(envPath);
const existing = parseEnv(envLocalPath);
const tokenSecret = usableSecret(existing.get("PAYMENT_TOKEN_SECRET"), "")
  ? existing.get("PAYMENT_TOKEN_SECRET")
  : randomBytes(32).toString("base64url");
const cronSecret = usableSecret(existing.get("CRON_SECRET"), "")
  ? existing.get("CRON_SECRET")
  : randomBytes(32).toString("base64url");

const settings = new Map(existing);
settings.set("STRIPE_SECRET_KEY", testSecretKey);
settings.set("NEXT_PUBLIC_STRIPE_PUBLISHABLE_KEY", testPublishableKey);
settings.set("STRIPE_WEBHOOK_SECRET", webhookSecret);
settings.set("APP_BASE_URL", inherited.get("APP_BASE_URL") || "http://localhost:3000");
settings.set("PAYMENT_TOKEN_SECRET", tokenSecret);
settings.set(
  "PAYMENTS_DB_PATH",
  inherited.get("PAYMENTS_DB_PATH") || ".data/solid-payments.sqlite"
);
settings.set("CRON_SECRET", cronSecret);

const header = [
  "# Generated by `npm run stripe:setup-local`.",
  "# Local secrets only. This file is gitignored.",
  "",
];
const body = [...settings.entries()].map(([key, value]) => `${key}=${value}`);
writeFileSync(envLocalPath, [...header, ...body, ""].join("\n"), {
  mode: 0o600,
});
chmodSync(envLocalPath, 0o600);

console.log("Configured .env.local with:");
console.log("- Stripe test secret key (restricted CLI key)");
console.log("- Stripe test publishable key");
console.log("- Stripe CLI webhook signing secret");
console.log("- generated payment-token and scheduler secrets");
console.log("- local SQLite payment database path");
